export function getRanksForModality(modality: string): GraduationRank[] {
  if (GRADUATION_GUIDES[modality]) return GRADUATION_GUIDES[modality].ranks;
  if (modality === 'Judo' || modality === 'Wrestling') return GRADUATION_GUIDES['Judo e Wrestling'].ranks;
  if (modality === 'Karate' || modality === 'Taekwondo') return GRADUATION_GUIDES['Karate e Taekwondo'].ranks;
  return GRADUATION_GUIDES['Muay Thai'].ranks;
}

export function getInitials(name: string): string {
  const parts = (name || 'SP').trim().split(/\s+/);
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return `${parts[0][0]}${parts[parts.length - 1][0]}`.toUpperCase();
}

